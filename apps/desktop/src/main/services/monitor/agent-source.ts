/**
 * 远端监控代理（Python 3，仅标准库）。
 *
 * ## 为什么要一个常驻代理
 * 旧实现每次采样都 `ssh exec` 起一个 `sh collect.sh`：每次都要 fork shell、
 * 重新读一遍 `/proc`、CPU/网络的速率还得靠"两次采样 + 临时文件"凑。
 * 3 秒一档时单是进程启动就吃掉几十毫秒，而且**速率永远滞后一个周期**。
 *
 * 代理的做法不一样：
 * - 常驻进程，把上一次的 CPU/网络/磁盘计数器留在内存里 → 速率是"真增量"，不是估算；
 * - 只监听 `127.0.0.1`，**不对外开端口**；桌面端经 SSH direct-tcpip 通道访问（见 agent.ts），
 *   所以既不需要在服务器上开防火墙，也不怕被同网段扫到；
 * - 请求带 token（状态文件 0600），同机的其他用户也读不到；
 * - 空闲 15 分钟自动退出并清理状态文件 —— 不给服务器留"僵尸服务"。
 *
 * ## 兼容性
 * 只依赖 Python 3.6+ 标准库。服务器没有 python3 时，采集器会**自动回退**
 * 到原来的 shell 脚本模式（行为不变），不影响任何已有功能。
 */

